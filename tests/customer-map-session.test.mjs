import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const app = readFileSync(new URL("../App.js", import.meta.url), "utf8");
const trackingHook = readFileSync(new URL("../src/hooks/useTracking.js", import.meta.url), "utf8");
const nativeMap = readFileSync(new URL("../src/components/OpenStreetMap.native.js", import.meta.url), "utf8");
const fleetMap = readFileSync(new URL("../src/components/LiveFleetMap.native.js", import.meta.url), "utf8");
const appConfig = readFileSync(new URL("../app.config.js", import.meta.url), "utf8");
const sessionStore = readFileSync(new URL("../src/services/session.js", import.meta.url), "utf8");

assert.match(app, /import OpenStreetMap from "\.\/src\/components\/OpenStreetMap"/);
assert.doesNotMatch(app, /import MapView, .*PROVIDER_GOOGLE/);
assert.match(app, /error\.status === 403 && error\.code === "ACCOUNT_INACTIVE"/);
assert.doesNotMatch(app, /error\.status === 404 \|\|/);
assert.match(nativeMap, /react-native-webview/);
assert.match(nativeMap, /openstreetmap\.org/);
assert.match(appConfig, /"expo-channel-name": "production"/);
assert.match(appConfig, /version: "1\.0\.22"/);
assert.match(sessionStore, /SecureStore\.setItemAsync\(SESSION_KEY/);
assert.match(sessionStore, /SecureStore\.deleteItemAsync\(SESSION_KEY\)/);
assert.match(app, /sessionStore\.clear\(\)\.catch\(\(\) => \{\}\)\.finally/);
assert.match(app, /<LiveFleetMap selected=\{bike\} vehicles=\{allFleetVehicles\} route=\{route\}/);
assert.match(fleetMap, /vehicles\s*\.filter\(vehicle => validPoint\(vehicle\.location\)\)\s*\.map\(vehicle =>/);
assert.match(fleetMap, /routePoints/);
assert.match(app, /fresh tracker report shows the vehicle is stationary/);
assert.match(app, /label: "Messages"/);
assert.match(app, /shownMessageNotificationIds/);
assert.match(app, /Jixels message/);
assert.match(app, /Open Messages/);
assert.match(app, /Recent messages|Messages<\/Text>/);
assert.match(app, /secureTextEntry=\{isSecure && !passwordVisible\}/);
assert.match(app, /eye-off-outline/);
assert.match(app, /const navigate = key =>/);
assert.match(app, /setScreen\(key\)/);
assert.match(app, /setSession\(null\)/);
assert.match(trackingHook, /const routeSequence = useRef\(0\)/, "route loading must use a sequence independent from frequent location polling");
assert.match(trackingHook, /routeSequence\.current === sequence/, "a live location refresh must not discard a valid route response");
assert.match(trackingHook, /routeError/, "route loading errors must be kept separate from live location polling errors");
assert.match(trackingHook, /setLoadedMotorcycle\(null\)/, "switching selected vehicles must clear the previous vehicle snapshot");
assert.match(trackingHook, /socket\?\.disconnect\(\)/);
assert.match(fleetMap, /map\.fitBounds\(routeLine\.getBounds\(/, "loading a historical route must bring the route into view");
assert.match(fleetMap, /routePoint=L\.circleMarker/, "a single returned GPS point must be visible even when a line cannot be drawn");
assert.match(trackingHook, /const POLL_INTERVAL_MS = 16_000/, "automatic location refresh must stay just under the provider's four-reads-per-minute limit");
assert.match(trackingHook, /setInterval\(poll, POLL_INTERVAL_MS\)/, "location refresh must continue automatically while the tracking screen is active");
assert.match(fleetMap, /L\.map\('map',\{zoomControl:false\}\)/, "Leaflet's default zoom controls must not overlap the vehicle search bar");
assert.match(fleetMap, /L\.control\.zoom\(\{position:'topright'\}\)/, "zoom controls must be grouped on the right below the search bar");
assert.match(fleetMap, /\.leaflet-top\.leaflet-right\{top:60px\}/, "zoom controls must sit below the search bar");
assert.match(fleetMap, /#follow-bike\{position:absolute;z-index:700;top:126px;right:12px;display:flex;width:42px;height:42px;.*border-radius:50%/, "follow control must be a compact circular map button below zoom controls");
assert.match(fleetMap, /followButton\.setAttribute\('aria-label',label\)/, "compact follow button must retain an accessible state label");
assert.match(app, /currentSpeedKph \?\? "—"/, "missing or stale tracker speed must not be displayed as zero");
assert.match(app, /setNow\(Date\.now\(\)\), 5000\)/, "the displayed last-update age must refresh every five seconds");
assert.match(fleetMap, /selectedPositionOutsideMap=selectedTarget&&!map\.getBounds\(\)\.contains\(selectedTarget\)/, "new tracker points outside the viewport must trigger recentering");
assert.match(fleetMap, /\(\(followSelected&&selectedPositionChanged\)\|\|selectedPositionOutsideMap\)/, "the selected bike must be brought back into view when it leaves the map");

console.log("Customer map and session regression checks passed.");
